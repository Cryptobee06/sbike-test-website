const formatDate = (dateString, locale) => {
  const date = new Date(dateString);
  return new Intl.DateTimeFormat(locale, {
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  }).format(date);
};

function formatInline(text) {
  return text
    .replace(/\*\*(.*?)\*\*/g, '<strong class="font-semibold text-gray-900">$1</strong>')
    .replace(/\*(.*?)\*/g, '<em class="italic text-gray-700">$1</em>');
}

function MarkdownContent({ content }) {
  const lines = content.split('\n');
  let html = '';
  let inList = false;

  for (const line of lines) {
    if (line.startsWith('# ')) {
      if (inList) { html += '</ul>'; inList = false; }
      html += `<h1 class="text-xl md:text-3xl lg:text-4xl font-bold text-gray-900 mb-4 mt-2">${formatInline(line.slice(2))}</h1>`;
    } else if (line.startsWith('## ')) {
      if (inList) { html += '</ul>'; inList = false; }
      html += `<h2 class="text-lg md:text-xl lg:text-2xl font-bold text-gray-900 mt-10 mb-3 pl-4 border-l-4 border-primary-500">${formatInline(line.slice(3))}</h2>`;
    } else if (line.startsWith('### ')) {
      if (inList) { html += '</ul>'; inList = false; }
      html += `<h3 class="text-lg font-semibold text-gray-800 mt-6 mb-2">${formatInline(line.slice(4))}</h3>`;
    } else if (line.startsWith('- ')) {
      if (!inList) { html += '<ul class="my-4 space-y-2">'; inList = true; }
      html += `<li class="flex items-start gap-2 text-gray-600 leading-relaxed"><span class="mt-1.5 w-2 h-2 rounded-full bg-primary-500 flex-shrink-0"></span><span>${formatInline(line.slice(2))}</span></li>`;
    } else if (line.trim() === '') {
      if (inList) { html += '</ul>'; inList = false; }
    } else {
      if (inList) { html += '</ul>'; inList = false; }
      html += `<p class="text-gray-600 leading-relaxed mb-4">${formatInline(line)}</p>`;
    }
  }
  if (inList) html += '</ul>';

  return <div className="max-w-none" dangerouslySetInnerHTML={{ __html: html }} />;
}

